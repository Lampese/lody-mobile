// Emits SwiftUI/UIKit sources and the icon asset catalog for iOS.
import { parseHex } from './tokens.mjs'
import { pathsToSvg } from './svg.mjs'

const SWIFT_KEYWORDS = new Set([
  'default', 'case', 'in', 'is', 'as', 'do', 'if', 'for', 'let', 'var', 'func', 'return',
  'switch', 'where', 'while', 'repeat', 'import', 'init', 'self', 'Self', 'super', 'true', 'false', 'nil',
])
const id = (name) => (SWIFT_KEYWORDS.has(name) ? `\`${name}\`` : name)
const header = (source) => `// Generated by design-system/scripts/build.mjs from ${source}. Do not edit.\n`
const doc = (text, indent) => (text ? `${indent}/// ${text}\n` : '')

function rgba(hex) {
  const { r, g, b, a } = parseHex(hex)
  return `0x${[r, g, b, a].map((v) => v.toString(16).toUpperCase().padStart(2, '0')).join('')}`
}

function colors(list) {
  const swiftUI = list
    .map((c) => `${doc(c.description, '    ')}    public static let ${id(c.name)} = Color(uiColor: LodyUIColor.${id(c.name)})`)
    .join('\n')
  const uiKit = list
    .map((c) => `    public static let ${id(c.name)} = UIColor(lodyLight: ${rgba(c.light)}, dark: ${rgba(c.dark)})`)
    .join('\n')
  return `${header('tokens/color.json')}
import SwiftUI
import UIKit

/// Semantic colors. Every value follows the trait collection's light / dark style.
public enum LodyColor {
${swiftUI}
}

/// UIKit mirror of \`LodyColor\` for views that are not SwiftUI.
public enum LodyUIColor {
${uiKit}
}

extension UIColor {
    convenience init(lodyLight light: UInt32, dark: UInt32) {
        self.init { traits in
            UIColor(lodyRGBA: traits.userInterfaceStyle == .dark ? dark : light)
        }
    }

    convenience init(lodyRGBA rgba: UInt32) {
        self.init(
            red: CGFloat((rgba >> 24) & 0xFF) / 255,
            green: CGFloat((rgba >> 16) & 0xFF) / 255,
            blue: CGFloat((rgba >> 8) & 0xFF) / 255,
            alpha: CGFloat(rgba & 0xFF) / 255
        )
    }
}
`
}

function typography({ families, styles }) {
  const statics = styles
    .map(
      (s) =>
        `${doc(s.description, '    ')}    static let ${id(s.name)} = LodyTextStyle(fontName: "${s.postScriptName}", size: ${s.size}, lineHeight: ${s.lineHeight}, tracking: ${s.tracking}, dynamicType: .${s.dynamicType})`,
    )
    .join('\n')
  const files = families.flatMap((f) => f.faces.map((face) => `        "${face.resourceName}",`)).join('\n')
  return `${header('tokens/typography.json')}
import CoreGraphics

public extension LodyTextStyle {
${statics}

    static let all: [LodyTextStyle] = [${styles.map((s) => `.${id(s.name)}`).join(', ')}]
}

public enum LodyFontFiles {
    /// Bundled .ttf resource names, registered by \`LodyFonts.register()\`.
    public static let all = [
${files}
    ]
}
`
}

function metrics({ groups, motion }) {
  const enums = Object.entries(groups)
    .map(([group, items]) => {
      const name = `Lody${group[0].toUpperCase()}${group.slice(1)}`
      const body = items
        .map((t) => `${doc(t.description, '    ')}    public static let ${id(t.name)}: CGFloat = ${t.value}`)
        .join('\n')
      return `public enum ${name} {\n${body}\n}`
    })
    .join('\n\n')
  const durations = motion.durations
    .map((d) => `${doc(d.description, '    ')}    public static let ${id(d.name)}: TimeInterval = ${d.value / 1000}`)
    .join('\n')
  const easings = motion.easings
    .map(
      (e) =>
        `    public static func ${id(e.name)}(duration: TimeInterval = base) -> Animation {\n        .timingCurve(${e.value.join(', ')}, duration: duration)\n    }`,
    )
    .join('\n\n')
  return `${header('tokens/dimension.json')}
import SwiftUI

${enums}

public enum LodyMotion {
${durations}

${easings}
}
`
}

function icons(names) {
  const cases = names.map((n) => `    case ${id(n)} = "lody.icon.${n}"`).join('\n')
  return `${header('icons/manifest.json')}
import SwiftUI
import UIKit

/// Lucide-derived icons shared with Android. Rendered as template images: tint with
/// \`.foregroundStyle(...)\` and size with \`.frame\` (see \`LodyIconSize\`).
public enum LodyIcon: String, CaseIterable, Sendable {
${cases}

    public var image: Image { Image(rawValue) }
    public var uiImage: UIImage? { UIImage(named: rawValue) }
}
`
}

function assetCatalog(iconPaths, strokeWidth) {
  const out = {}
  const info = { author: 'xcode', version: 1 }
  out['generated/ios/LodyIcons.xcassets/Contents.json'] = JSON.stringify({ info }, null, 2) + '\n'
  for (const [name, paths] of iconPaths) {
    const dir = `generated/ios/LodyIcons.xcassets/lody.icon.${name}.imageset`
    out[`${dir}/${name}.svg`] = pathsToSvg(paths, strokeWidth)
    out[`${dir}/Contents.json`] =
      JSON.stringify(
        {
          images: [{ filename: `${name}.svg`, idiom: 'universal' }],
          info,
          properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'template' },
        },
        null,
        2,
      ) + '\n'
  }
  return out
}

export function emitSwift({ colors: colorList, typography: type, dimensions, iconPaths, iconStroke }) {
  const dir = 'generated/ios/LodyDesignSystem'
  return {
    [`${dir}/LodyColor.swift`]: colors(colorList),
    [`${dir}/LodyTextStyles.swift`]: typography(type),
    [`${dir}/LodyMetrics.swift`]: metrics(dimensions),
    [`${dir}/LodyIcon.swift`]: icons([...iconPaths.keys()]),
    ...assetCatalog(iconPaths, iconStroke),
  }
}
