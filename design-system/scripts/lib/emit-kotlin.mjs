// Emits Jetpack Compose sources for Android. Fonts are not copied: the app adds
// design-system/fonts as a res source dir, so R.font.lody_* resolves.
import { parseHex } from './tokens.mjs'

export const ANDROID_PACKAGE = 'app.lody.android.designsystem'
export const ANDROID_R = 'app.lody.android.R'

const header = (source) =>
  `// Generated by design-system/scripts/build.mjs from ${source}. Do not edit.\n\npackage ${ANDROID_PACKAGE}\n`
const kdoc = (text, indent) => (text ? `${indent}/** ${text} */\n` : '')
const pascal = (name) => name[0].toUpperCase() + name.slice(1)
const float = (v) => `${v}f`

function argb(hex) {
  const { r, g, b, a } = parseHex(hex)
  return `0x${[a, r, g, b].map((v) => v.toString(16).toUpperCase().padStart(2, '0')).join('')}`
}

function colors(list) {
  const fields = list.map((c) => `${kdoc(c.description, '    ')}    val ${c.name}: Color,`).join('\n')
  const set = (mode) => list.map((c) => `    ${c.name} = Color(${argb(c[mode])}),`).join('\n')
  return `${header('tokens/color.json')}
import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

/** Semantic colors. Read the active set through \`LodyTheme.colors\`. */
@Immutable
class LodyColors(
${fields}
) {
    fun entries(): List<Pair<String, Color>> = listOf(
${list.map((c) => `        "${c.id}" to ${c.name},`).join('\n')}
    )
}

val LodyLightColors = LodyColors(
${set('light')}
)

val LodyDarkColors = LodyColors(
${set('dark')}
)
`
}

function typography({ families, styles }) {
  const familyVals = families
    .map((f) => {
      const fonts = f.faces.map((face) => `    Font(R.font.${face.resourceName}, FontWeight.W${face.weight}),`).join('\n')
      return `val Lody${pascal(f.name)}FontFamily = FontFamily(\n${fonts}\n)`
    })
    .join('\n\n')
  const fields = styles.map((s) => `${kdoc(s.description, '    ')}    val ${s.name}: TextStyle,`).join('\n')
  const values = styles
    .map(
      (s) =>
        `    ${s.name} = lodyTextStyle(Lody${pascal(s.family)}FontFamily, FontWeight.W${s.weight}, ${s.size}, ${s.lineHeight}, ${float(s.tracking)}),`,
    )
    .join('\n')
  return `${header('tokens/typography.json')}
import androidx.compose.runtime.Immutable
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.Font
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.text.style.LineHeightStyle
import androidx.compose.ui.unit.sp
import ${ANDROID_R}

${familyVals}

/** Type scale. Read the active set through \`LodyTheme.typography\`. */
@Immutable
class LodyTypography(
${fields}
) {
    fun entries(): List<Pair<String, TextStyle>> = listOf(
${styles.map((s) => `        "${s.name}" to ${s.name},`).join('\n')}
    )
}

val LodyDefaultTypography = LodyTypography(
${values}
)

// Center glyphs in the full line box and keep the leading on both ends, which
// matches how the iOS runtime pads lines to the same height.
private val LodyLineHeightStyle = LineHeightStyle(
    alignment = LineHeightStyle.Alignment.Center,
    trim = LineHeightStyle.Trim.None,
)

private fun lodyTextStyle(family: FontFamily, weight: FontWeight, size: Int, lineHeight: Int, tracking: Float) =
    TextStyle(
        fontFamily = family,
        fontWeight = weight,
        fontSize = size.sp,
        lineHeight = lineHeight.sp,
        letterSpacing = tracking.sp,
        lineHeightStyle = LodyLineHeightStyle,
    )
`
}

function dimensions({ groups, numbers, motion }) {
  const objects = Object.entries(groups)
    .map(([group, items]) => {
      const body = items.map((t) => `${kdoc(t.description, '    ')}    val ${t.name} = ${t.value}.dp`).join('\n')
      const all = items.map((t) => `        "${t.name}" to ${t.name},`).join('\n')
      return `object Lody${pascal(group)} {\n${body}\n\n    val all: List<Pair<String, Dp>> = listOf(\n${all}\n    )\n}`
    })
    .join('\n\n')
  const numberObjects = Object.entries(numbers)
    .map(([group, items]) => {
      const body = items.map((t) => `${kdoc(t.description, '    ')}    const val ${t.name} = ${float(t.value)}`).join('\n')
      return `object Lody${pascal(group)} {\n${body}\n}`
    })
    .join('\n\n')
  const springs = motion.springs
    .map(
      (t) =>
        `${kdoc(`${t.description ?? ''} SwiftUI: duration ${t.value.duration}s, bounce ${t.value.bounce}.`.trim(), '    ')}    fun <T> ${t.name}(): SpringSpec<T> = spring(dampingRatio = ${float(t.dampingRatio)}, stiffness = ${float(t.stiffness)})`,
    )
    .join('\n')
  const durations = motion.durations
    .map((d) => `${kdoc(d.description, '    ')}    const val ${d.name}Millis = ${d.value}`)
    .join('\n')
  const easings = motion.easings
    .map((e) => `    val ${e.name}: Easing = CubicBezierEasing(${e.value.map(float).join(', ')})`)
    .join('\n')
  return `${header('tokens/dimension.json')}
import androidx.compose.animation.core.CubicBezierEasing
import androidx.compose.animation.core.Easing
import androidx.compose.animation.core.SpringSpec
import androidx.compose.animation.core.spring
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

${objects}

${numberObjects}

object LodyMotion {
${durations}

${easings}
}

/** Springs matching iOS \`LodySpring\` (SwiftUI duration / bounce converted to stiffness / damping). */
object LodySpring {
${springs}
}
`
}

function elevation(levels) {
  const vals = levels
    .map((e) => `${kdoc(e.description, '    ')}    val ${e.name} = LodyElevation(blur = ${e.blur}.dp, y = ${e.y}.dp) { it.${e.color} }`)
    .join('\n')
  return `${header('tokens/elevation.json')}
import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Shadow for custom floating surfaces. Apply with
 * \`Modifier.dropShadow(shape, LodyElevations.md.shadow())\`.
 * [blur] is in Figma / CSS terms; [color] resolves against the active [LodyColors].
 */
@Immutable
class LodyElevation(val blur: Dp, val y: Dp, val color: (LodyColors) -> Color)

object LodyElevations {
${vals}
}
`
}

function icons(iconPaths, strokeWidth, overrides) {
  const vals = [...iconPaths]
    .map(([name, paths]) => {
      const args =
        [pascal(name), ...paths].map((arg) => `            "${arg}",`).join('\n') +
        (overrides[name] === undefined ? '' : `\n            strokeWidth = ${float(overrides[name])},`)
      return `    val ${pascal(name)}: ImageVector by lazy {\n        lodyIcon(\n${args}\n        )\n    }`
    })
    .join('\n\n')
  return `${header('icons/manifest.json')}
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

/**
 * Lucide-derived icons shared with iOS. Use with \`Icon(LodyIcons.Inbox, contentDescription, tint = ...)\`;
 * size with \`Modifier.size(LodyIconSize.md)\`.
 */
object LodyIcons {
${vals}

    val all: List<Pair<String, ImageVector>> by lazy {
        listOf(
${[...iconPaths.keys()].map((n) => `            "${n}" to ${pascal(n)},`).join('\n')}
        )
    }
}

private fun lodyIcon(name: String, vararg paths: String, strokeWidth: Float = ${float(strokeWidth)}): ImageVector =
    ImageVector.Builder(
        name = "Lody.$name",
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = 24f,
        viewportHeight = 24f,
    ).apply {
        for (d in paths) {
            addPath(
                pathData = addPathNodes(d),
                stroke = SolidColor(Color.Black),
                strokeLineWidth = strokeWidth,
                strokeLineCap = StrokeCap.Round,
                strokeLineJoin = StrokeJoin.Round,
            )
        }
    }.build()
`
}

export function emitKotlin({ colors: colorList, typography: type, dimensions: dims, elevation: levels, iconPaths, iconStroke, iconStrokeWidths }) {
  const dir = `generated/android/${ANDROID_PACKAGE.replaceAll('.', '/')}`
  return {
    [`${dir}/LodyColors.kt`]: colors(colorList),
    [`${dir}/LodyTypography.kt`]: typography(type),
    [`${dir}/LodyDimens.kt`]: dimensions(dims),
    [`${dir}/LodyElevation.kt`]: elevation(levels),
    [`${dir}/LodyIcons.kt`]: icons(iconPaths, iconStroke, iconStrokeWidths),
  }
}
