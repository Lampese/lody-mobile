// Emits generated/preview.html: a static review sheet of every token in both
// modes, so design changes can be judged without building either app.
import { contrastRatio } from './contrast.mjs'
import { pathsToSvg } from './svg.mjs'

const esc = (s) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c])
const cssHex = (hex) => (hex.length === 9 ? `#${hex.slice(1)}` : hex)

export function emitPreview({ colors, typography, dimensions, iconPaths, iconStroke }) {
  const byId = new Map(colors.map((c) => [c.id, c]))
  const vars = (mode) => colors.map((c) => `--${c.id.replace('.', '-')}: ${cssHex(c[mode])};`).join(' ')
  const v = (tokenId) => `var(--${tokenId.replace('.', '-')})`

  const fontFaces = typography.families
    .flatMap((f) =>
      f.faces.map(
        (face) =>
          `@font-face { font-family: lody-${f.name}; font-weight: ${face.weight}; src: url(../fonts/font/${face.resourceName}.ttf); }`,
      ),
    )
    .join('\n')

  const colorRows = colors
    .map((c) => {
      const swatch = (mode) =>
        `<td><span class="sw" style="background:${cssHex(c[mode])}"></span><code>${c[mode]}</code></td>`
      return `<tr><td><code>${c.id}</code><div class="desc">${esc(c.description)}</div></td>${swatch('light')}${swatch('dark')}</tr>`
    })
    .join('\n')

  const typeRows = typography.styles
    .map(
      (s) =>
        `<div class="type-row"><div class="meta"><code>${s.name}</code><br>${s.size}/${s.lineHeight} · ${s.weight} · ${s.tracking}pt</div>` +
        `<div style="font-family:lody-${s.family};font-weight:${s.weight};font-size:${s.size}px;line-height:${s.lineHeight}px;letter-spacing:${s.tracking}px;color:${v('text.primary')}">` +
        `${s.family === 'mono' ? 'const session = await lody.open(id) // 会话' : '同一个 worktree 多个 tabs · Agent finished the review'}</div></div>`,
    )
    .join('\n')

  const iconCells = [...iconPaths]
    .map(([name, paths]) => `<div class="icon">${pathsToSvg(paths, iconStroke, 'currentColor')}<code>${name}</code></div>`)
    .join('\n')

  const rows = [
    ['stateRunning', 'state.running', '同一个 worktree 多个 tabs', 'Running · 2m'],
    ['stateWaiting', 'state.waiting', 'Review auth middleware changes', 'Needs approval'],
    ['stateDone', 'state.done', '为 loro swift 添加 debug trait 的支持', 'Done · PR #3935'],
    ['stateIdle', 'state.idle', '实现 refresh token', 'Backlog'],
  ]
  const icon = (name) => pathsToSvg(iconPaths.get(name), iconStroke, 'currentColor')
  const mockList = rows
    .map(
      ([glyph, color, title, meta]) =>
        `<div class="row"><span style="color:${v(color)}">${icon(glyph)}</span><div><div class="t-body">${esc(title)}</div><div class="t-foot">${esc(meta)}</div></div></div>`,
    )
    .join('')
  const mock = `<div class="mock"><div class="t-large">Sessions</div><div class="t-sub sec">Running</div>${mockList}
    <div class="composer"><span class="t-body" style="color:${v('text.placeholder')}">Ask Lody…</span><span class="send">${icon('send')}</span></div></div>`

  const contrast = (mode) =>
    `${mode}: text.primary/bg.base ${contrastRatio(byId.get('text.primary')[mode], byId.get('bg.base')[mode]).toFixed(1)}`

  const dims = Object.entries(dimensions.groups)
    .map(
      ([group, items]) =>
        `<h3>${group}</h3><div class="dims">${items.map((t) => `<div><code>${t.name}</code> ${t.value}</div>`).join('')}</div>`,
    )
    .join('')

  return `<!doctype html>
<!-- Generated by design-system/scripts/build.mjs. Do not edit. -->
<html><head><meta charset="utf-8"><title>Lody mobile tokens</title>
<style>
${fontFaces}
body { margin: 0; font-family: lody-sans, sans-serif; background: #f4f4f6; color: #1a1a1e; }
main { max-width: 1100px; margin: 0 auto; padding: 32px; }
h1 { font-size: 28px; } h2 { margin-top: 48px; font-size: 20px; } h3 { font-size: 14px; margin: 20px 0 8px; }
code { font-family: lody-mono, monospace; font-size: 12px; }
.desc { color: #797983; font-size: 12px; }
table { border-collapse: collapse; width: 100%; background: #fff; }
td { border-bottom: 1px solid #eee; padding: 6px 10px; vertical-align: middle; }
.sw { display: inline-block; width: 28px; height: 20px; border-radius: 4px; border: 1px solid #0002; vertical-align: middle; margin-right: 8px; }
.modes { display: grid; grid-template-columns: 1fr 1fr; gap: 16px; }
.mode { padding: 20px; border-radius: 14px; background: ${v('bg.base')}; color: ${v('text.primary')}; }
.light { ${vars('light')} } .dark { ${vars('dark')} }
.type-row { display: grid; grid-template-columns: 140px 1fr; gap: 12px; padding: 8px 0; border-bottom: 1px solid ${v('border.subtle')}; }
.type-row .meta { font-size: 11px; color: ${v('text.tertiary')}; }
.icons { display: grid; grid-template-columns: repeat(auto-fill, minmax(84px, 1fr)); gap: 8px; color: ${v('icon.primary')}; }
.icon { display: flex; flex-direction: column; align-items: center; gap: 6px; padding: 10px 0; }
.icon svg { width: 20px; height: 20px; } .icon code { font-size: 10px; color: ${v('text.tertiary')}; }
.dims { display: flex; flex-wrap: wrap; gap: 6px 18px; font-size: 13px; }
.mock { width: 360px; margin: 0 auto; }
.mock .row { display: flex; gap: 12px; align-items: center; min-height: 48px; padding: 8px 0; border-bottom: 1px solid ${v('border.subtle')}; }
.mock .row svg { width: 20px; height: 20px; display: block; }
.t-large { font-weight: 700; font-size: 28px; line-height: 34px; letter-spacing: -0.59px; }
.t-sub { font-weight: 500; font-size: 14px; line-height: 20px; color: ${v('text.tertiary')}; }
.sec { margin-top: 16px; }
.t-body { font-size: 16px; line-height: 22px; letter-spacing: -0.18px; }
.t-foot { font-size: 13px; line-height: 18px; color: ${v('text.secondary')}; }
.composer { margin-top: 24px; display: flex; align-items: center; justify-content: space-between; min-height: 48px; padding: 0 6px 0 16px; border-radius: 20px; background: ${v('bg.raised')}; border: 1px solid ${v('border.default')}; }
.send { width: 36px; height: 36px; border-radius: 999px; display: grid; place-items: center; background: ${v('accent.default')}; color: ${v('text.onAccent')}; }
.send svg { width: 20px; height: 20px; }
</style></head>
<body><main>
<h1>Lody mobile design tokens</h1>
<p class="desc">${contrast('light')} · ${contrast('dark')}</p>

<h2>Sample screen</h2>
<div class="modes"><div class="mode light">${mock}</div><div class="mode dark">${mock}</div></div>

<h2>Type</h2>
<div class="modes"><div class="mode light">${typeRows}</div><div class="mode dark">${typeRows}</div></div>

<h2>Icons</h2>
<div class="modes"><div class="mode light"><div class="icons">${iconCells}</div></div><div class="mode dark"><div class="icons">${iconCells}</div></div></div>

<h2>Color</h2>
<table><tr><td></td><td><b>Light</b></td><td><b>Dark</b></td></tr>
${colorRows}
</table>

<h2>Dimensions (pt = dp)</h2>
${dims}
</main></body></html>
`
}
