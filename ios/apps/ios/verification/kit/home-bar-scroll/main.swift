import Foundation
var state = HomeBarScrollState()
state.update(offset: -40, scrolling: true, threshold: 24)
assert(!state.collapsed, "Pull to refresh stays expanded")
state.update(offset: 12, scrolling: true, threshold: 24)
assert(!state.collapsed, "Small movements must not flicker")
state.update(offset: 100, scrolling: false, threshold: 24)
assert(!state.collapsed, "Data/layout updates do not collapse the bar")
state.update(offset: 100, scrolling: true, threshold: 24)
assert(state.collapsed)
state.update(offset: 10, scrolling: true, threshold: 24)
assert(state.collapsed, "Scrolling back expands only at the top")
state.update(offset: 0, scrolling: false, threshold: 24)
assert(!state.collapsed, "Returning to the top restores the bar")
print("Home bar scroll behavior passed")
